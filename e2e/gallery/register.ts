// The moment register: every shared ui part with a gallery page
// (/gallery/<Part>, e2e/gallery/<Part>.tsx) and every moment it renders.
// One list. A part renders each STATES and AWKWARD moment, or skips it with a
// one-line reason. The guard (src/__tests__/gallery-register.test.ts) fails
// when a ui part file is in neither PARTS nor PENDING, when a rendered moment
// has no cell on the page, or when a skip has no reason. A new part or state
// goes in here and onto its gallery page first.

